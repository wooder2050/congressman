/**
 * 2026년 국정감사 — /issues/audit-2026 편집 데이터.
 *
 * 원칙:
 * - 상임위별 일정은 해당 위원회가 채택한 국정감사계획서를 보도한 2026년 9월 기사로 확인한 것만 적는다.
 *   확인되지 않은 위원회는 status "pending"으로 두고 날짜를 추측해 채우지 않는다.
 *   (검색 결과에 과거 연도 기사가 섞여 나온다 — 교육위 "10월 8~24일"은 2024년 기사였다.)
 * - 쟁점은 발언자·주체를 밝혀 인용하고, 여야 입장을 함께 적는다.
 * - 갱신: 국감 기간 중 계획서가 추가로 확정되면 committees를, 주요 공방이 생기면 issues를 고치고
 *   updatedAt을 바꾼다. 실제 회의 일정은 daily sync가 채우는 일정 데이터에서 자동으로 보여 준다.
 */

export interface AuditSource {
  title: string;
  url: string;
}

interface AuditDay {
  /** "10-06" 또는 "10-11~10-22"처럼 표시용 날짜 */
  date: string;
  /** 허브 목록용 짧은 표기 — 기관이 많으면 "○○ 등 N곳" */
  target: string;
  /** 상임위별 페이지용 피감기관 전체 목록(계획서 원문 기준) */
  detail?: string;
  /** 장소·기관증인·현장시찰 등 그날의 보충 설명 */
  note?: string;
}

interface AuditWitness {
  name: string;
  /** 증인·참고인·기관증인 구분 */
  kind?: string;
  affiliation: string;
  /** 출석 예정일 "10-06" */
  date?: string;
  /** 신문 요지 */
  topic?: string;
  /** adopted = 위원회 의결로 채택, requested = 신청만 됨 */
  status: "adopted" | "requested";
}

/**
 * 일정·명단 변경 기록 — 2026-10-03부터 기록한다(과거 변경을 추측해 채우지 않는다).
 * 위원회 게시판에 수정본이 올라오거나 국회 공개 일정·보도로 바뀐 것이 확인되면 추가한다.
 */
export interface AuditChange {
  /** 변경을 확인한 날 "2026-10-02" */
  on: string;
  kind: "일정" | "장소" | "증인" | "기관";
  /** 한 줄 요약 */
  summary: string;
  /** 바뀌기 전 → 후 (해당하면) */
  before?: string;
  after?: string;
  source?: AuditSource;
}

export interface AuditCommittee {
  /** /committees/[name] 경로와 같은 정식 명칭 */
  name: string;
  short: string;
  /**
   * confirmed = 국정감사계획서 의결 확인(국회 게시판 원문 또는 의결 보도)
   * reported = 계획서 원문 확인 전(의결 전이거나 원문 미공개), 보도된 예정 일정만 있음 — 날짜가 바뀔 수 있다고 표시한다
   * pending = 일정 정보 없음
   */
  status: "confirmed" | "reported" | "pending";
  /** 계획서 의결일 "2026-09-21" */
  resolvedOn?: string;
  /**
   * 위원회 게시판(계획서·참고자료)을 마지막으로 확인한 날 "2026-10-03".
   * 이날까지 원문과 다른 점이 없었다는 뜻이지, 이후 바뀌지 않는다는 보장은 아니다.
   */
  checkedAt?: string;
  /** 확인된 변경 이력(최근 것이 앞) */
  changes?: AuditChange[];
  /** 위원회 감사 기간(표시용) */
  period?: string;
  /** 대상 기관 규모 등 한 줄 요약 */
  scope?: string;
  days: AuditDay[];
  /** 증인·참고인 등 보충 메모 */
  note?: string;
  /**
   * 상임위별 페이지 검색 제목에 넣을 주요 피감기관 — 검색어가 "2026 국정감사 일정 국방부"처럼
   * 부처명으로 들어온다(9/28 네이버·GSC). 검색에서 쓰는 약칭 위주로 2~3개.
   */
  titleAgencies?: string;
  /** 상임위별 페이지(/issues/audit-2026/[위원회명]) 첫 문단 — 이 위원회 감사를 한 단락으로 요약한 편집 해설 */
  summary?: string;
  witnesses?: AuditWitness[];
  /** 이 위원회에만 해당하는 쟁점 — 상임위별 페이지에만 보인다(허브는 AUDIT_2026.issues) */
  issues?: AuditIssue[];
  sources: AuditSource[];
}

interface AuditIssue {
  title: string;
  committees: string[];
  body: string;
  /** 발언·입장 인용 — 주체를 밝힌다 */
  quotes?: { who: string; text: string }[];
  sources: AuditSource[];
}

