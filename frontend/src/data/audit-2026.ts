/** 상임위별 국감 페이지 경로 — /committees/[name]과 같은 정식 명칭을 쓴다 */
export function auditCommitteePath(name: string): string {
  return `${AUDIT_2026.path}/${encodeURIComponent(name)}`;
}

/**
 * 상임위별 페이지를 공개(생성·색인·광고)할 수 있는지.
 * 계획서가 확인됐고, 편집 요약을 쓰고, 날짜별 일정이 3일 이상 확인된 위원회만 연다 —
 * 일정 한두 줄뿐인 페이지는 허브 카드와 다를 게 없는 얇은 페이지라 만들지 않는다.
 */
export function isAuditCommitteePageReady(c: AuditCommittee): boolean {
  return c.status === "confirmed" && !!c.summary && c.days.length >= 3;
}
